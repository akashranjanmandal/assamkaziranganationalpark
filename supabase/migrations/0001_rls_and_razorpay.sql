-- ════════════════════════════════════════════════════════════════════════
-- Migration 0001: Row Level Security + Razorpay columns + missing tables
--
-- This migration is ADDITIVE and safe to run against a database that already
-- has reference-db-schema.sql applied. It does NOT overwrite that file. It:
--   1. Defines car_rental_bookings, vehicles (missing from reference-db-schema.sql
--      but referenced throughout admin.html / car-rental.html).
--   2. Adds trending_itineraries (also referenced but not defined in the
--      reference schema — inferred from admin.html's day-by-day builder and
--      itineraries.html / index.html's read queries).
--   3. Adds Razorpay columns to bookings (razorpay_order_id, razorpay_payment_id)
--      and a real "paid"/"verified" payment_status distinct from the legacy
--      'pending_confirmation' flow (manual UPI/QR screenshot review).
--   4. Enables/repairs RLS policies for the anon role across every table that
--      the browser touches directly, matching the security model in
--      MIGRATION_NOTES.md: anon can INSERT bookings/car_rental_bookings/reviews
--      and SELECT active vehicles/trending_itineraries/drop_route_prices/
--      approved reviews, and nothing else. All other operations (confirm,
--      approve, CRUD) go through service-role-only Next.js API routes.
-- ════════════════════════════════════════════════════════════════════════

-- ── 1. Razorpay + payment status columns on bookings ──────────────────────
ALTER TABLE bookings
  ADD COLUMN IF NOT EXISTS razorpay_order_id TEXT,
  ADD COLUMN IF NOT EXISTS razorpay_payment_id TEXT,
  ADD COLUMN IF NOT EXISTS razorpay_signature TEXT;

-- payment_status values used across the app:
--   'pending_confirmation' — legacy manual UPI/QR screenshot flow, awaiting admin review
--   'paid'                 — Razorpay payment verified server-side (HMAC signature check passed)
--   'confirmed'            — admin has confirmed the booking (safari slot guaranteed)
-- No CHECK constraint added, to stay compatible with any existing rows using
-- other ad-hoc values from the old site; application code is the source of truth.

-- ── 2. Vehicles (car rental fleet) ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  capacity INT NOT NULL,
  price_per_day NUMERIC,
  description TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE vehicles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "service_all_vehicles" ON vehicles;
CREATE POLICY "service_all_vehicles" ON vehicles FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_read_active_vehicles" ON vehicles;
CREATE POLICY "anon_read_active_vehicles" ON vehicles FOR SELECT TO anon USING (active = true);

-- ── 3. Trending itineraries ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS trending_itineraries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  duration TEXT NOT NULL,
  price_from TEXT,
  short_desc TEXT,
  days_json TEXT,       -- JSON-encoded [{ title, activities: string[] }] — day-by-day builder in admin
  details TEXT,          -- pre-rendered HTML snippet shown in the trending card (built server-side by admin)
  active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE trending_itineraries ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "service_all_trending_itineraries" ON trending_itineraries;
CREATE POLICY "service_all_trending_itineraries" ON trending_itineraries FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_read_active_trending_itineraries" ON trending_itineraries;
CREATE POLICY "anon_read_active_trending_itineraries" ON trending_itineraries FOR SELECT TO anon USING (active = true);

-- ── 4. Car rental bookings (enquiries) ─────────────────────────────────────
CREATE TABLE IF NOT EXISTS car_rental_bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id BIGINT REFERENCES vehicles(id) ON DELETE SET NULL,
  vehicle_name TEXT,
  itinerary TEXT NOT NULL,
  num_passengers INT NOT NULL DEFAULT 1,
  num_days INT,
  pickup_date DATE,
  pickup_location TEXT,
  total_cost NUMERIC,
  customer_name TEXT,
  customer_phone TEXT,
  customer_email TEXT,
  upi_ref TEXT,
  payment_screenshot_url TEXT,
  status TEXT NOT NULL DEFAULT 'pending', -- 'pending' | 'confirmed'
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE car_rental_bookings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "service_all_car_rental_bookings" ON car_rental_bookings;
CREATE POLICY "service_all_car_rental_bookings" ON car_rental_bookings FOR ALL TO service_role USING (true) WITH CHECK (true);

-- anon may only ever INSERT an enquiry — never read, update or delete rows
-- (this differs from the original static site, which used the service_role
-- key client-side and could therefore SELECT everyone else's bookings too).
DROP POLICY IF EXISTS "anon_insert_car_rental_bookings" ON car_rental_bookings;
CREATE POLICY "anon_insert_car_rental_bookings" ON car_rental_bookings FOR INSERT TO anon WITH CHECK (true);

-- ── 5. Lock down bookings / reviews / drop_route_prices to the intended
--      anon-role surface (INSERT-only on bookings; existing reviews policies
--      already match this pattern in reference-db-schema.sql, re-asserted
--      here idempotently; SELECT-only active rows on drop_route_prices). ──

ALTER TABLE bookings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "service_all_bookings" ON bookings;
CREATE POLICY "service_all_bookings" ON bookings FOR ALL TO service_role USING (true) WITH CHECK (true);

-- anon can INSERT a new booking (the public booking flow) but can never
-- SELECT/UPDATE/DELETE bookings — that would leak every guest's Aadhaar
-- path, phone number and payment reference to any visitor with the anon key.
DROP POLICY IF EXISTS "anon_insert_bookings" ON bookings;
CREATE POLICY "anon_insert_bookings" ON bookings FOR INSERT TO anon WITH CHECK (true);
DROP POLICY IF EXISTS "anon_select_bookings" ON bookings;
DROP POLICY IF EXISTS "anon_update_bookings" ON bookings;
DROP POLICY IF EXISTS "anon_delete_bookings" ON bookings;

ALTER TABLE reviews ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "service_all_reviews" ON reviews;
CREATE POLICY "service_all_reviews" ON reviews FOR ALL TO service_role USING (true) WITH CHECK (true);
-- Re-assert the reference schema's existing anon policies idempotently:
DROP POLICY IF EXISTS "anon_read_reviews" ON reviews;
CREATE POLICY "anon_read_reviews" ON reviews FOR SELECT TO anon USING (approved = true);
DROP POLICY IF EXISTS "anon_insert_reviews" ON reviews;
CREATE POLICY "anon_insert_reviews" ON reviews FOR INSERT TO anon WITH CHECK (true);

ALTER TABLE drop_route_prices ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "service_all_drop_route_prices" ON drop_route_prices;
CREATE POLICY "service_all_drop_route_prices" ON drop_route_prices FOR ALL TO service_role USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "anon_read_drop_route_prices" ON drop_route_prices;
CREATE POLICY "anon_read_drop_route_prices" ON drop_route_prices FOR SELECT TO anon USING (active = true);

-- ── 6. Private Storage bucket for uploads (Aadhaar, payment screenshots) ───
-- Unlike reference-db-schema.sql's `assam` bucket (created PUBLIC, with an
-- anon INSERT policy — meaning anyone with the anon key could both upload
-- and publicly read every uploaded Aadhaar card), this bucket is PRIVATE.
-- All reads/writes go through server-side Next.js API routes using the
-- service_role client (see app/api/upload/route.ts and
-- app/api/files/[key]/route.ts), which apply folder allowlisting and a
-- 15MB size cap before ever touching storage.
INSERT INTO storage.buckets (id, name, public)
VALUES ('assam-uploads', 'assam-uploads', false)
ON CONFLICT (id) DO UPDATE SET public = false;

-- No anon storage.objects policies are created for this bucket — the
-- service_role key (server-side only) bypasses RLS entirely, which is the
-- only way this bucket is ever accessed.
